// City page: sherlock-research/<slug>.html
// Content comes from src/data/cities/<slug>.json.
import { esc, scriptJSON, slugify, formatPrice } from '../lib.mjs';
import * as partials from '../partials.mjs';

export function render(c, site, ctx) {
  const url = `${site.url}/${c.slug}.html`;
  const metro = `${c.name}, ${c.state}`;
  const metroSlug = slugify(metro);
  const cityPlan = site.plans.find((p) => p.key === 'city');
  const title = `${metro} Market Intelligence`;
  if (!site.metros.includes(metro)) {
    throw new Error(`${c.slug}: "${metro}" is not in site.json metros, so its City-Specific report cannot be ordered.`);
  }

  const breadcrumbLD = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: `${site.url}/` },
      { '@type': 'ListItem', position: 2, name: 'Reports', item: `${site.url}/reports.html` },
      { '@type': 'ListItem', position: 3, name: metro, item: url },
    ],
  };

  const reportHref = (r) => `${r.slug}-report.html?metro=${metroSlug}#purchase`;

  return `<!DOCTYPE html>
<!-- Generated by scripts/build.mjs from src/templates/city.mjs and src/data/cities/${c.slug}.json. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
<title>${esc(title)} — ${esc(site.name)}</title>
<meta name="description" content="${esc(c.metaDescription)}">
<link rel="canonical" href="${url}">
<meta property="og:type" content="website">
<meta property="og:title" content="${esc(title)} — ${esc(site.name)}">
<meta property="og:description" content="${esc(c.ogDescription)}">
<meta property="og:url" content="${url}">
${partials.head(site, { css: ['city.css'] })}
<script type="application/ld+json">
${scriptJSON(breadcrumbLD)}
</script>
</head>
<body>

${partials.nav(site, ctx, { current: `${c.slug}.html` })}

<main id="main">
<header class="hero">
  <div class="container">
    <nav class="breadcrumb" aria-label="Breadcrumb">
      <ol>
        <li><a href="index.html">Home</a></li>
        <li><a href="reports.html">Reports</a></li>
        <li><span aria-current="page">${esc(metro)}</span></li>
      </ol>
    </nav>
    <div class="hero-grid">
      <div>
        <div class="hero-eyebrow">${esc(c.name)}, ${esc(c.stateName)}</div>
        <h1>Market intelligence,<br>built for <em>${esc(c.name)}</em>.</h1>
        <p class="hero-sub">${esc(c.intro)}</p>
        <div class="hero-cta-row">
          <a href="#reports" class="btn btn-primary btn-lg">Browse ${esc(c.name)} reports</a>
          <a href="sample.html" class="btn btn-outline btn-lg">Get a free sample</a>
        </div>
      </div>
      <div class="snapshot">
        <h2 class="snapshot-title">${esc(c.name)} at a glance</h2>
        <ul class="snapshot-stats">
          ${c.stats.map((s) => `<li><div class="v">${esc(s.value)}</div><div class="l">${esc(s.label)}</div></li>`).join('\n          ')}
        </ul>
        <div class="snapshot-label">Local data cuts available</div>
        <ul class="snapshot-list">
          ${ctx.reports.map((r) => `<li><a href="${reportHref(r)}"><span class="ic">${partials.industryIcon(r.slug, 18)}</span>${esc(r.name)}<span class="price">${esc(formatPrice(cityPlan))} →</span></a></li>`).join('\n          ')}
        </ul>
      </div>
    </div>
  </div>
</header>

<section class="reports-section" id="reports">
  <div class="container">
    <div class="section-head">
      <div class="eyebrow">City-specific reports</div>
      <h2>${ctx.reports.length} industry reports with <em>${esc(c.name)}</em> data built in.</h2>
      <p>${esc(c.reportsIntro)}</p>
    </div>
    <div class="reports-grid">
      ${ctx.reports.map((r) => `<a class="rep-card" href="${reportHref(r)}">
        <div class="ic">${partials.industryIcon(r.slug)}</div>
        <h3>${esc(r.name)} — ${esc(c.name)}</h3>
        <div class="meta">City-Specific Report · ${esc(formatPrice(cityPlan))}</div>
        <p>${esc(c.reportBlurbs[r.slug])}</p>
        <span class="more">Choose ${esc(c.name)} and buy →</span>
      </a>`).join('\n      ')}
    </div>
  </div>
</section>

<section class="why">
  <div class="container">
    <div class="section-head">
      <div class="eyebrow">Why local matters here</div>
      <h2>${c.insights.length} things <em>${esc(c.name)}</em> operators consistently underestimate.</h2>
    </div>
    <ol class="why-grid">
      ${c.insights.map((w, i) => `<li class="why-card">
        <div class="why-num" aria-hidden="true">0${i + 1}</div>
        <h3>${esc(w.title)}</h3>
        <p>${esc(w.text)}</p>
      </li>`).join('\n      ')}
    </ol>
  </div>
</section>

<section class="cta">
  <div class="container">
    <h2>Make a confident move in <em>${esc(c.name)}</em>.</h2>
    <p>Start with one report. If it doesn't give you a Monday-morning action, we'll refund it within 30 days.</p>
    <div class="cta-row">
      <a href="pricing.html?metro=${metroSlug}" class="btn btn-primary btn-lg">See pricing →</a>
      <a href="sample.html" class="btn btn-outline btn-lg">Get a free sample</a>
    </div>
  </div>
</section>
</main>

${partials.footer(site, ctx)}

</body>
</html>
`;
}
